# в распознавании языка и не влияет на метрики: оценка качества всегда идёт
# по чистой конфигурации (см. evaluation.py).


def _env_bool(name: str, default: bool) -> bool:
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() in {"1", "true", "yes", "on", "да"}


