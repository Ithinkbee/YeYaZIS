"""Приведение слова к латинице — основа викторины при взятии фигуры.

Смысл приёма в следующем. Русский и немецкий пользуются разными алфавитами,
и поэтому задача распознавания решается тривиально: достаточно взглянуть на
буквы. Если же русское слово записать латиницей («работа» → «rabota»), а у
немецкого свернуть умлауты («Wärme» → «waerme»), оба языка окажутся в одном
алфавите, и отличить их можно будет только по строению слова — по тем самым
сочетаниям букв, на которых работает метод N-грамм.

Получается, что игрок решает ровно ту задачу, которую решает система, но без
подсказки в виде алфавита. Попутно выясняется любопытное: обученные на
кириллице профили на транслитерации ошибаются, и человек оказывается точнее
системы (см. `tolmach/quiz.py`).
"""

from __future__ import annotations

#: практическая транслитерация кириллицы латиницей.
#: Порядок важен: многобуквенные соответствия должны проверяться раньше
#: однобуквенных, иначе «щ» превратится в «sh» + «ch».
RUSSIAN_MAP: dict[str, str] = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "yo",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "shch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}

#: свёртка немецкой диакритики — общепринятая замена при записи без умлаутов
GERMAN_MAP: dict[str, str] = {
    "ä": "ae", "ö": "oe", "ü": "ue", "ß": "ss",
}


def latinize(word: str, language: str) -> str:
    """Записывает слово латиницей по правилам своего языка.

    Русское слово транслитерируется, немецкое теряет диакритику. Слово,
    уже записанное латиницей без диакритики, возвращается без изменений.
    """
    word = word.strip().lower()
    table = RUSSIAN_MAP if language == "ru" else GERMAN_MAP
    return "".join(table.get(char, char) for char in word)


def is_cyrillic(word: str) -> bool:
    """Есть ли в слове кириллица."""
    return any("Ѐ" <= char <= "ӿ" for char in word)


def has_latin_diacritics(word: str) -> bool:
    """Есть ли в слове буквы, сразу выдающие немецкий."""
    return any(char in GERMAN_MAP for char in word.lower())


def looks_latin(word: str) -> bool:
    """Записано ли слово только базовой латиницей.

    Проверка нужна викторине: показывать игроку слово, в котором осталась
    кириллица или умлаут, бессмысленно — ответ был бы виден сразу.
    """
    return bool(word) and all("a" <= char <= "z" for char in word.lower())
