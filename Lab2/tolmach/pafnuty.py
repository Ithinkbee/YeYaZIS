def line(
    occasion: str,
    rng: random.Random | None = None,
    avoid: tuple[str, ...] | list[str] = (),
    **fields: str,
) -> str:
    """Реплика по поводу; для неизвестного повода — дежурная.

    `avoid` — недавно сказанное: такие варианты выбираются, только если
    других не осталось, чтобы паук не повторялся. `fields` подставляются в
    реплики о фигурах; реплика, которой нужных полей не передали, не
    выбирается.
    """
    variants = LINES.get(occasion) or LINES["idle"]
    candidates = [_fill(variant, fields) for variant in variants]
    candidates = [text for text in candidates if text] or [
        variant for variant in variants if "{" not in variant
    ] or list(variants)
    fresh = [text for text in candidates if text not in set(avoid)]
    return (rng or random).choice(fresh or candidates)


def _fill(variant: str, fields: dict[str, str]) -> str:
    try:
        return variant.format(**fields)
    except (KeyError, IndexError):
        return ""


def piece_fields(piece: str, square: str) -> dict[str, str]:
    """Поля реплики о фигуре: падежные формы названия и поле."""
    kind = piece.lower()
    nominative = PIECE_NOMINATIVE.get(kind, "фигура")
    accusative = PIECE_ACCUSATIVE.get(kind, "фигуру")
    return {
        "piece": accusative,
        "piece_acc_cap": accusative.capitalize(),
        "piece_nom": nominative,
        "piece_cap": nominative.capitalize(),
        "square": square,
    }


def greeting(page: str, rng: random.Random | None = None) -> str:
    """Реплика для угла страницы: своя для разделов, дежурная для остальных."""
    by_page = {"index": "collection", "compare": "compare", "check": "gate", "chess": "chess_start"}
    return line(by_page.get(page, "idle"), rng)
