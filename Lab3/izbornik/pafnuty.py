def line(
    occasion: str,
    rng: random.Random | None = None,
    avoid: tuple[str, ...] | list[str] = (),
    **fields: str,
) -> str:
    """Реплика по поводу или разделу; для неизвестного — дежурная.

    `avoid` — недавно сказанное: такие варианты выбираются, только если других
    не осталось. `fields` подставляются в реплики с полями; реплика, которой
    нужных полей не передали, не выбирается.
    """
    variants = LINES.get(occasion) or LINES["idle"]
    filled = [_fill(variant, fields) for variant in variants]
    candidates = [text for text in filled if text] or [v for v in variants if "{" not in v] or list(variants)
    fresh = [text for text in candidates if text not in set(avoid)]
    return (rng or random).choice(fresh or candidates)


def _fill(variant: str, fields: dict[str, str]) -> str:
    try:
        return variant.format(**fields)
    except (KeyError, IndexError):
        return ""


def client_lines(prefix: str) -> dict[str, list[str]]:
    """Реплики игры для браузера: бой и сапёр идут без обращений к серверу."""
    return {key: list(value) for key, value in LINES.items() if key.startswith(prefix + "_")}
