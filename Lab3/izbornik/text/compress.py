"""Сжатие предложений классического реферата.

Методичка допускает, что предложения реферата «возможно трансформированы»:
удалены вводные конструкции, заменены анафорические местоимения — ради
связности и меньшего объёма. Здесь выполняется безопасная часть этой работы:

* удаляются ссылки на литературу: «[3]», «[1, с. 45]», «[12–14]»;
* удаляются скобочные отсылки к рисункам и таблицам: «(рис. 2)», «(см. табл. 1)»,
  «(vgl. Abb. 3)»;
* в русском предложении удаляется вводная конструкция в начале: «Таким
  образом, …», «Кроме того, …», «Во-первых, …».

В немецком предложении вводное слово в начале не удаляется: немецкий порядок
слов требует, чтобы спрягаемый глагол стоял вторым, и «Außerdem ist das System
schnell» без первого слова превратилось бы в вопрос «ist das System schnell».

Замена местоимений требует разрешения анафоры и здесь не выполняется. Отбор
предложений от сжатия не зависит: сжимаются уже выбранные предложения.
"""

from __future__ import annotations

import re

_CITATION = re.compile(
    r"\s*\[\s*\d+(?:\s*[,;–-]\s*\d+)*(?:\s*[,;]\s*(?:с|c|s|S|p|pp|стр)\.\s*\d+(?:\s*[–-]\s*\d+)?)?\s*\]"
)
_FIGURE_REF = re.compile(
    r"\s*\((?:см\.\s*|vgl\.\s*|siehe\s*|s\.\s*)?(?:рис|рисунок|табл|таблица|abb|abbildung|tab|tabelle|fig)"
    r"\.?\s*[\d.,\s–-]*\)",
    re.I,
)

#: вводные конструкции (сравниваются с началом предложения без учёта регистра)
_INTRODUCTORY_RU = [
    "таким образом", "кроме того", "помимо этого", "помимо того", "более того",
    "во-первых", "во-вторых", "в-третьих", "в-четвертых", "в-четвёртых", "в-пятых",
    "следовательно", "итак", "однако", "впрочем", "между тем", "в частности",
    "например", "к примеру", "так", "наконец", "в итоге", "в результате",
    "с одной стороны", "с другой стороны", "в свою очередь", "по сути",
    "по-видимому", "по всей видимости", "конечно", "безусловно", "разумеется",
    "действительно", "очевидно", "вероятно", "возможно", "кстати", "в целом",
    "по мнению автора", "по мнению авторов", "как известно", "как правило",
    "как было сказано выше", "как отмечалось выше", "как видно", "иными словами",
    "другими словами", "то есть", "прежде всего", "в первую очередь", "в заключение",
]
_INTRODUCTORY_RU.sort(key=len, reverse=True)


def compress(sentence: str, language: str) -> str:
    """Сжатое предложение; если сжимать нечего, возвращается исходное."""
    text = _CITATION.sub("", sentence)
    text = _FIGURE_REF.sub("", text)
    if language == "ru":
        text = _drop_introductory(text)
    text = re.sub(r"\s+([,.;:!?…])", r"\1", text)
    text = re.sub(r"\s{2,}", " ", text).strip()
    return text or sentence


def _drop_introductory(text: str) -> str:
    lower = text.lower()
    for phrase in _INTRODUCTORY_RU:
        if lower.startswith(phrase) and lower[len(phrase):len(phrase) + 1] == ",":
            rest = text[len(phrase) + 1:].lstrip()
            if len(rest) < 20:
                return text
            return rest[:1].upper() + rest[1:]
    return text
