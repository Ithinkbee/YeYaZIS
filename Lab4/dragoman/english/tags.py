def upos(tag: str) -> str:
    entry = PENN.get(tag)
    if entry:
        return entry[0]
    return "PUNCT" if tag and not any(ch.isalnum() for ch in tag) else "X"


def describe(tag: str) -> str:
    entry = PENN.get(tag)
    return entry[1] if entry else "неизвестный тег"


def describe_deprel(label: str) -> str:
    if label in DEPRELS:
        return DEPRELS[label]
    base = label.split(":")[0]
    return DEPRELS.get(base, label)


def features(tag: str) -> dict[str, str]:
    """Грамматические признаки, которые следуют из тега: число, время, форма глагола, степень."""
    f: dict[str, str] = {}
    if tag in {"NN", "NNP"}:
        f["Number"] = "Sing"
    elif tag in {"NNS", "NNPS"}:
        f["Number"] = "Plur"
    elif tag == "VBZ":
        f.update(Number="Sing", Person="3", Tense="Pres", VerbForm="Fin")
    elif tag == "VBP":
        f.update(Tense="Pres", VerbForm="Fin")
    elif tag == "VBD":
        f.update(Tense="Past", VerbForm="Fin")
    elif tag == "VBN":
        f.update(Tense="Past", VerbForm="Part")
    elif tag == "VBG":
        f.update(VerbForm="Ger")
    elif tag == "VB":
        f["VerbForm"] = "Inf"
    elif tag in {"JJR", "RBR"}:
        f["Degree"] = "Cmp"
    elif tag in {"JJS", "RBS"}:
        f["Degree"] = "Sup"
    return f


FEATURE_NAMES = {
    "Number": {"Sing": "ед. ч.", "Plur": "мн. ч."},
    "Person": {"3": "3-е лицо"},
    "Tense": {"Pres": "наст. вр.", "Past": "прош. вр."},
    "VerbForm": {"Fin": "личная форма", "Part": "причастие", "Ger": "-ing-форма", "Inf": "инфинитив"},
    "Degree": {"Cmp": "сравн. степень", "Sup": "превосх. степень"},
}


def describe_features(tag: str) -> str:
    parts = []
    for name, value in features(tag).items():
        parts.append(FEATURE_NAMES.get(name, {}).get(value, value))
    return ", ".join(parts)
