def line(occasion: str, rng: random.Random | None = None, **fields: str) -> str:
    variants = LINES.get(occasion) or LINES["idle"]
    filled = []
    for variant in variants:
        try:
            filled.append(variant.format(**fields))
        except (KeyError, IndexError):
            continue
    candidates = filled or [v for v in variants if "{" not in v] or list(variants)
    return (rng or random).choice(candidates)


def client_lines(prefix: str) -> dict[str, list[str]]:
    return {key: list(value) for key, value in LINES.items() if key.startswith(prefix + "_") or key == prefix}
